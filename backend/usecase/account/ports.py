from datetime import datetime
from typing import Protocol
from uuid import UUID

from domain.account.account import Account
from domain.account.identity import ProviderIdentity


class AccountStore(Protocol):
    async def get(self, user_id: UUID) -> Account | None: ...

    async def get_or_create(self, identity: ProviderIdentity, created_at: datetime) -> Account: ...

    async def save(self, account: Account) -> Account | None: ...

    async def delete(self, user_id: UUID) -> None: ...

    async def set_avatar(self, user_id: UUID, body: bytes, content_type: str) -> Account | None: ...

    async def clear_avatar(self, user_id: UUID) -> Account | None: ...

    async def read_avatar(self, key: UUID) -> tuple[bytes, str] | None: ...


class OAuthCodes(Protocol):
    async def mint_state(self, state: str, provider: str, browser: str, expires_at: datetime) -> None: ...

    async def take_state(self, state: str, provider: str, now: datetime) -> str | None: ...

    async def mint_handoff(self, code: str, user_id: UUID, browser: str, expires_at: datetime) -> None: ...

    async def take_handoff(self, code: str, browser: str, now: datetime) -> UUID | None: ...


class TokenIssuer(Protocol):
    def issue(self, user_id: UUID): ...

    def issue_access(self, user_id: UUID) -> str: ...

    def read(self, token: str, kind: str): ...


class Revocations(Protocol):
    async def revoke(self, token: str, expires_at: datetime) -> None: ...

    async def is_revoked(self, token: str) -> bool: ...


class OAuthProvider(Protocol):
    name: str

    def authorization_url(self, state: str) -> str: ...

    async def fetch_identity(self, code: str) -> ProviderIdentity: ...
